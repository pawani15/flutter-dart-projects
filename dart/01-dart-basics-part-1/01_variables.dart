void main() {
  // Variables and data types
  String name = "Pawani";
  int age = 30;
  double height = 164.0;
  bool isStudent = true;

  // Type inference
  var city = "Bhubaneswar";

  // Final and const
  final country = "India";
  const double pi = 3.14159;

  print("Name: $name");
  print("Age: $age");
  print("Height: $height");
  print("Student: $isStudent");
  print("City: $city");
  print("Country: $country");
  print("PI: $pi");
}